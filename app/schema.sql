CREATE TABLE IF NOT EXISTS users (
 id INTEGER PRIMARY KEY, email TEXT NOT NULL UNIQUE, password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS clients (
 id INTEGER PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES users(id),
 name TEXT NOT NULL, environment TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS analyses (
 id INTEGER PRIMARY KEY, client_id INTEGER NOT NULL REFERENCES clients(id),
 hostname TEXT NOT NULL, inventory TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'Em revisão',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS findings (
 id INTEGER PRIMARY KEY, analysis_id INTEGER NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
 rule_id TEXT NOT NULL, title TEXT NOT NULL, severity TEXT NOT NULL,
 evidence TEXT NOT NULL, recommendation TEXT NOT NULL,
 decision TEXT NOT NULL DEFAULT 'Pendente', note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS events (
 id INTEGER PRIMARY KEY, analysis_id INTEGER NOT NULL REFERENCES analyses(id) ON DELETE CASCADE,
 actor_id INTEGER NOT NULL REFERENCES users(id), action TEXT NOT NULL,
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS clients_owner ON clients(owner_id);
CREATE INDEX IF NOT EXISTS findings_analysis ON findings(analysis_id);
